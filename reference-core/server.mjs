#!/usr/bin/env node
/**
 * Reference agent core: implements the PRCheck.live agent-core protocol (docs/agent-core-protocol.md)
 * so the engine can be built and tested against it. It is a contract test double, not the myDiya agents:
 *   impact    myDelta's job, done here by component overlap plus route-level hints
 *   verifier  delivers checks from a small pattern library; anything else fails honestly
 *   suite     (re)delivers story checks from the library, carrying the Lead's feedback
 * The myDiya agent core implements the same endpoints with its agents.
 *   AGENT_CORE_TOKEN=... PORT=4100 node reference-core/server.mjs
 */
import http from 'http';
import { readFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROTOCOL = 'prcheck.agent-core/v1', VERSION = '0.2.0-reference';
const TOKEN = process.env.AGENT_CORE_TOKEN || '';
const DELAY = Number(process.env.AGENT_CORE_DELAY_MS ?? 600);
const lib = (p) => JSON.parse(readFileSync(join(HERE, 'library', p), 'utf8'));
const missions = new Map(); let seq = 100;

// minimal glob: ** any path, * any segment characters
const glob = (g) => new RegExp('^' + g.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*\*/g, '\u0000').replace(/\*/g, '[^/]*').replace(/\u0000/g, '.*') + '$');
const SOURCE = /^(src|db|lib|app|public|server|client)\//;

const AGENTS = {
  impact: ['myDelta'],
  verifier: ['myClara', 'myTessa', 'myGenie', 'myNexa'],
  suite: ['myClara', 'myTessa', 'myGenie'],
};

function impact(p) {
  const comps = Object.entries(p.components ?? {});
  const changed = new Set(), unknown = [];
  for (const f of p.changedFiles ?? []) {
    const hit = comps.filter(([, globs]) => globs.some((g) => glob(g).test(f))).map(([c]) => c);
    hit.forEach((c) => changed.add(c));
    if (!hit.length && SOURCE.test(f)) unknown.push(f);
  }
  const selected = [];
  for (const s of p.stories ?? []) {
    const shared = (s.components ?? []).filter((c) => changed.has(c));
    if (unknown.length) selected.push({ story: s.key, because: `myDelta: ${unknown[0]} is not mapped to a component; impact unknown`, confidence: 'low' });
    else if (shared.length) selected.push({ story: s.key, because: `myDelta: the change touches ${shared.join(', ')}`, confidence: 'high' });
  }
  return { changedComponents: [...changed], unknownFiles: unknown, selected, confidence: unknown.length ? 'low' : 'high' };
}

function verifier(p) {
  const idx = lib('verifiers/index.json'), e = idx[p.check];
  if (!e) throw new Error(`The reference core has no pattern for ${p.check}. The myDiya agent core generates it from the rule with its agents.`);
  let code = readFileSync(join(HERE, 'library', 'verifiers', e.file), 'utf8');
  if (p.feedback) code = code.replace(/\n(test\()/, `\n// Regenerated after review: ${p.feedback.replace(/\n/g, ' ')}\n$1`);
  return { files: [{ path: `generated/${e.file}`, content: code }],
    entries: Object.entries(idx).filter(([, v]) => v.file === e.file).map(([check, v]) => ({ check, file: `generated/${e.file}`, fault: { seeded: v.fault, result: 'FAILED', by: 'myGenie' } })) };
}

function suite(p) {
  const s = lib('suites/index.json')[p.story];
  const out = [];
  for (const id of p.criteria ?? []) {
    const c = s?.[id];
    if (!c) throw new Error(`The reference core has no checks for ${p.story} ${id}. The myDiya agent core designs them from the criterion with its agents.`);
    out.push({ id, checks: c.checks, fault: { seeded: c.fault, result: 'FAILED', by: 'myGenie' }, note: p.feedback ? `Regenerated after review: ${p.feedback}` : 'Generated from the criterion' });
  }
  // The spec file is returned whole: here the current one, with the Lead's feedback recorded at the top.
  const spec = p.spec ? [{ path: p.spec.path, content: p.feedback ? `// Regenerated by the agent core after review: ${p.feedback.replace(/\n/g, ' ')}\n${p.spec.content.replace(/^\/\/ Regenerated by the agent core after review:.*\n/, '')}` : p.spec.content }] : [];
  return { files: spec, criteria: out };
}

const HANDLERS = { impact, verifier, suite };

function send(res, code, body) { res.writeHead(code, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)); }
http.createServer((req, res) => {
  if (TOKEN && req.headers.authorization !== `Bearer ${TOKEN}`) return send(res, 401, { error: 'UNAUTHORIZED' });
  let body = ''; req.on('data', (d) => (body += d)); req.on('end', () => {
    const url = new URL(req.url, 'http://x');
    if (req.method === 'GET' && url.pathname === '/v1/info')
      return send(res, 200, { name: 'mydiya-agent-core', implementation: 'reference', version: VERSION, protocol: PROTOCOL, missions: Object.keys(HANDLERS), agents: [...new Set(Object.values(AGENTS).flat())] });
    if (req.method === 'POST' && url.pathname === '/v1/missions') {
      let m; try { m = JSON.parse(body || '{}'); } catch { return send(res, 400, { error: 'BAD_JSON' }); }
      if (!HANDLERS[m.kind]) return send(res, 400, { error: 'UNKNOWN_KIND', message: `Unknown mission kind ${m.kind}` });
      if (m.protocol !== PROTOCOL) return send(res, 400, { error: 'PROTOCOL', message: `Expected ${PROTOCOL}` });
      const id = `M-${++seq}`, rec = { id, kind: m.kind, status: 'queued', agents: AGENTS[m.kind], core: { name: 'mydiya-agent-core', version: VERSION }, submittedAt: new Date().toISOString() };
      missions.set(id, rec);
      setTimeout(() => { rec.status = 'running'; setTimeout(() => {
        try { rec.result = HANDLERS[m.kind](m.payload ?? {}); rec.status = 'delivered'; }
        catch (e) { rec.status = 'failed'; rec.error = e.message; }
        rec.finishedAt = new Date().toISOString();
      }, DELAY); }, 50);
      return send(res, 202, { id, status: 'queued' });
    }
    const m = url.pathname.match(/^\/v1\/missions\/([\w-]+)$/);
    if (req.method === 'GET' && m) { const rec = missions.get(m[1]); return rec ? send(res, 200, rec) : send(res, 404, { error: 'NOT_FOUND' }); }
    send(res, 404, { error: 'NOT_FOUND' });
  });
}).listen(Number(process.env.PORT ?? 4100), () => console.log(`reference agent core ${VERSION} on :${process.env.PORT ?? 4100}`));
